export function t(key: string, lang: AppLanguage = 'pt', replacements?: Record<string, string | number>): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.pt;
  let text = dictionary[key] || TRANSLATIONS.pt[key] || key;

  if (replacements) {
    Object.entries(replacements).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }

  return text;
}
